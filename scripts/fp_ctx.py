#!/usr/bin/env python3
"""Field contexts of libjbn (layout: src/amd64/ref/fp_ctx@n.jinc).

A context packs the constants of a modulus P (odd, 1 < P < R = 2^(64*n)):

    glob_ctx = [ P | R-P | R mod P | R^2 mod P | -P^-1 mod 2^64 ]

Usage:
  fp_ctx.py gen N P [--title T]   print a constants file (Jasmin) for P with
                                  N limbs (P in decimal or 0x-hex)
  fp_ctx.py convert OLD NEW       convert an old constants file (glob_P,
                                  glob_mP, glob_Pm2, glob_P0i, glob_exp0,
                                  glob_rMP) into a context file; the old
                                  constants are checked against P, other
                                  globals are kept verbatim
"""
import re
import sys

W = 2 ** 64


def ctx_words(P, n):
    """The context of P, as a list of 4*n+1 words."""
    R = W ** n
    if not (P % 2 == 1 and 1 < P < R):
        raise ValueError("P must be odd and 1 < P < 2^(64*%d)" % n)
    limbs = lambda x: [(x >> (64 * i)) % W for i in range(n)]
    u0 = (-pow(P, -1, W)) % W
    return limbs(P) + limbs(R - P) + limbs(R % P) + limbs(R * R % P) + [u0]


def ctx_decl(P, n, name="glob_ctx"):
    w = ctx_words(P, n)
    parts = [("P", w[0:n]),
             ("R - P, with R = 2^(64*nlimbs)", w[n:2 * n]),
             ("R mod P (1 in Montgomery form)", w[2 * n:3 * n]),
             ("R^2 mod P", w[3 * n:4 * n]),
             ("-P^-1 mod 2^64", w[4 * n:])]
    out = ["u64[4*nlimbs+1] %s = {" % name]
    for k, (title, ws) in enumerate(parts):
        out.append("  // %s" % title)
        for j, x in enumerate(ws):
            last = k == len(parts) - 1 and j == len(ws) - 1
            out.append("  0x%016x%s" % (x, "" if last else ","))
    out.append("};")
    return "\n".join(out)


def header(title, n):
    return ("/* %s.\n"
            "   glob_ctx is the field context (layout: fp_ctx@n.jinc), generated by\n"
            "   scripts/fp_ctx.py. Required in a namespace whose nlimbs is %d. */\n"
            % (title, n))


# --- parsing of the old constants files -------------------------------------

DECL = re.compile(r"\bu64\s*(\[[^\]]*\])?\s+(\w+)\s*=\s*(\{.*?\}|[^;{]*?)\s*;",
                  re.S)


def strip_comments(s):
    s = re.sub(r"/\*.*?\*/", " ", s, flags=re.S)
    return re.sub(r"//[^\n]*", " ", s)


def words(init):
    return [int(t, 0) for t in re.findall(r"0x[0-9a-fA-F]+|\b\d+\b",
                                          strip_comments(init))]


def value(ws):
    return sum(x * W ** i for i, x in enumerate(ws))


def convert(old, new):
    text = open(old).read()
    m = re.match(r"\s*/\*.*?\*/", text, re.S)
    head = m.group(0) if m else ""
    body = text[m.end():] if m else text
    # declarations, outside comments; the text before each (its comments)
    # belongs to it
    scrubbed = re.sub(r"/\*.*?\*/|//[^\n]*",
                      lambda c: re.sub(r"[^\n]", " ", c.group(0)), body, flags=re.S)
    decls, extras, pos = {}, [], 0
    for d in DECL.finditer(scrubbed):
        name = d.group(2)
        decls[name] = words(body[d.start(3):d.end(3)])
        if name not in ("glob_P", "glob_mP", "glob_Pm2", "glob_P0i",
                        "glob_exp0", "glob_rMP"):
            extras.append(body[pos:d.end()].strip("\n"))
        pos = d.end()
    tail = body[pos:].strip()
    n = len(decls["glob_P"])
    P = value(decls["glob_P"])
    R = W ** n
    checks = [("glob_mP", value(decls["glob_mP"]), R - P),
              ("glob_Pm2", value(decls["glob_Pm2"]), P - 2),
              ("glob_P0i", value(decls["glob_P0i"]), (-pow(P, -1, W)) % W),
              ("glob_exp0", value(decls["glob_exp0"]), R % P),
              ("glob_rMP", value(decls["glob_rMP"]), R * R % P)]
    bad = [c for c in checks if c[1] != c[2]]
    for name, got, want in bad:
        print("%s: %s is not as expected (0x%x instead of 0x%x)"
              % (old, name, got, want), file=sys.stderr)
    if bad:
        sys.exit(1)
    # title: the first sentence of the old header
    h = re.sub(r"\s+", " ", head.strip("/* \n"))
    t = re.match(r"(.*?), under the names", h)
    s = re.match(r"SPECIFIC (\S+) CODE", h)
    title = (t.group(1) if t else
             "%s: constants of the prime field modulo P" % s.group(1) if s else h)
    out = [header(title, n), ctx_decl(P, n)]
    out += ["", *extras] if extras else []
    out += ["", tail] if tail else []
    open(new, "w").write("\n".join(out) + "\n")
    kept = [DECL.search(strip_comments(e)).group(2) for e in extras]
    print("%s -> %s (nlimbs = %d%s)"
          % (old, new, n, ", kept: " + " ".join(kept) if kept else ""))


def main(argv):
    if len(argv) >= 3 and argv[0] == "gen":
        n, P = int(argv[1]), int(argv[2], 0)
        title = argv[argv.index("--title") + 1] if "--title" in argv else \
            "Constants of the prime field modulo P"
        print(header(title, n) + "\n" + ctx_decl(P, n))
    elif len(argv) == 3 and argv[0] == "convert":
        convert(argv[1], argv[2])
    else:
        print(__doc__, file=sys.stderr)
        sys.exit(2)


if __name__ == "__main__":
    main(sys.argv[1:])
