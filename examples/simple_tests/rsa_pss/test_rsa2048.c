static void words_print(const char *str, const uint64_t *x, int n) {
  int i;
  printf("%s = [ ", str);
  for (i = 0; i < n; i++) printf("%s0x%016llx", i ? ", " : "", (unsigned long long)x[i]);
  printf(" ]\n");
}

static int check(const char *str, int k, const uint64_t *exp, const uint64_t *got, int n) {
  int ok = memcmp(exp, got, n * sizeof(uint64_t)) == 0;
  if (k < 0) printf("TESTING %s: %s\n", str, ok ? "OK" : "FAILED");
  else printf("TESTING %s (message %d): %s\n", str, k, ok ? "OK" : "FAILED");
  if (!ok) { words_print("Expecting", exp, n); words_print("Got", got, n); }
  return ok;
}

int main(void) {
  uint64_t PK[PK_WORDS], SK[SK_WORDS], x[NLIMBS], y[NLIMBS];
  int k, ok = 1;

  memset(PK, 0xa5, sizeof PK);
  memset(SK, 0xa5, sizeof SK);
  rsa_init(PK, SK);
  ok &= check("rsa_init: PK", -1, PK_exp, PK, PK_WORDS);
  ok &= check("rsa_init: SK", -1, SK_exp, SK, SK_WORDS);

  for (k = 0; k < NTESTS; k++) {
    rsa_enc(x, msg[k], PK);
    ok &= check("rsa_enc(m) == m^e", k, enc[k], x, NLIMBS);
    rsa_dec(y, x, SK);
    ok &= check("rsa_dec(rsa_enc(m)) == m", k, msg[k], y, NLIMBS);
    rsa_dec(x, msg[k], SK);
    ok &= check("rsa_dec(m) == m^d", k, sig[k], x, NLIMBS);
    rsa_enc(y, x, PK);
    ok &= check("rsa_enc(rsa_dec(m)) == m", k, msg[k], y, NLIMBS);
  }
  printf(ok ? "ALL OK\n" : "SOME TESTS FAILED\n");
  return ok ? 0 : 1;
}
